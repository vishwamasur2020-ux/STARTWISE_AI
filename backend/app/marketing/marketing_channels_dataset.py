from typing import List, Dict, Any


class MarketingChannelData:
    def __init__(
        self,
        channel_name: str,
        platform: str,
        target_audience: List[str],
        business_categories: List[str],
        minimum_budget: float,
        recommended_budget: float,
        cost_level: str,          # Low, Medium, High
        reach_level: str,         # Local, Regional, National, Global
        conversion_potential: str,# High, Medium, Moderate
        local_business_score: float, # 0.0 to 10.0
        digital_score: float,       # 0.0 to 10.0
        b2b_score: float,           # 0.0 to 10.0
        b2c_score: float,           # 0.0 to 10.0
        difficulty: str,            # Easy, Moderate, Advanced
        time_to_results: str,       # Immediate, Fast (1-2 weeks), Medium (1 month), Slow (3-6 months)
        description: str,
        best_for: str,
    ):
        self.channel_name = channel_name
        self.platform = platform
        self.target_audience = target_audience
        self.business_categories = business_categories
        self.minimum_budget = minimum_budget
        self.recommended_budget = recommended_budget
        self.cost_level = cost_level
        self.reach_level = reach_level
        self.conversion_potential = conversion_potential
        self.local_business_score = local_business_score
        self.digital_score = digital_score
        self.b2b_score = b2b_score
        self.b2c_score = b2c_score
        self.difficulty = difficulty
        self.time_to_results = time_to_results
        self.description = description
        self.best_for = best_for

    def to_dict(self) -> Dict[str, Any]:
        """Convert channel data to dictionary."""
        return {
            "channel_name": self.channel_name,
            "platform": self.platform,
            "target_audience": self.target_audience,
            "business_categories": self.business_categories,
            "minimum_budget": self.minimum_budget,
            "recommended_budget": self.recommended_budget,
            "cost_level": self.cost_level,
            "reach_level": self.reach_level,
            "conversion_potential": self.conversion_potential,
            "local_business_score": self.local_business_score,
            "digital_score": self.digital_score,
            "b2b_score": self.b2b_score,
            "b2c_score": self.b2c_score,
            "difficulty": self.difficulty,
            "time_to_results": self.time_to_results,
            "description": self.description,
            "best_for": self.best_for,
        }


